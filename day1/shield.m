% shield(t) —— 问题 1 判定函数（严格按建模手《遮蔽规则·一页纸》实现）
% 输入 : t —— 时刻 (s)，t = 0 为警戒雷达发现导弹、受领任务的时刻
% 输出 : flag = 1  该时刻云团挡住了「导弹 → 真目标」的视线；否则 0
%        d    = 云团中心到视线段的距离 (m)，可选输出，用于边界核对
%
% 一页纸规则：
%   §1 视线段  L(t) = [M1(t), T]
%        M1(t) = (20000 − 298.5t, 0, 2000 − 29.85t)   （导弹，朝假目标斜降）
%        T     = (0, 200, 5)                          （真目标简化点，固定）
%   §2 d(t) = C(t) 到线段 [M1(t), T] 的最短距离（投影法，λ 截断到 [0,1]）
%        C(t)  = (17188, 0, 1736.5 − 3(t−5.1))        （云团中心，起爆后只下沉）
%   §3 遮蔽条件（两条同时满足）：d(t) ≤ 10 且 5.1 ≤ t ≤ 25.1
%
% 常数来源：17188 = 17800 − 120×1.5 − 120×3.6（平抛水平位移）；
%           1736.5 ≈ 1800 − ½×9.8×3.6² = 1736.496（一页纸取一位小数，
%           对应关键假设 3：g = 9.8）。
% ⚠ 本函数与 main_Q1.m 公式必须一致，改动请两边同步。

    %% ---- 常数（与一页纸相同）----
    T_pt   = [0, 200, 5];      % 真目标简化点 T（§1）
    t_det  = 5.1;              % 起爆时刻 (s)
    T_life = 20;               % 起爆后有效时长 (s)
    R      = 10;               % 有效遮蔽半径 (m)

    d = NaN;
    flag = 0;

    %% ---- §3 条件二：时间窗 5.1 ≤ t ≤ 25.1 ----
    if t < t_det || t > t_det + T_life
        return;                % 云团还没形成 / 已消散 → 不遮蔽
    end

    %% ---- §1 §2：时刻 t 的三个位置 ----
    A = [20000 - 298.5*t, 0, 2000 - 29.85*t];    % M1(t)
    B = T_pt;                                    % T
    P = [17188, 0, 1736.5 - 3*(t - t_det)];      % C(t)

    %% ---- §3 条件一：d(t) ≤ 10 ----
    d = point_to_segment_dist(P, A, B);
    if d <= R
        flag = 1;
    end
end

