function flag = shield(t)
% shield(t) —— 问题 1 判定函数（任务单第 6 步）
% 输入：时刻 t（秒，t = 0 为警戒雷达发现导弹、受领任务的时刻）
% 输出：flag = 1  该时刻云团挡住了「导弹 → 真目标」的视线
%       flag = 0  没挡住
%
% 判定规则（与《全队必读》已知条件表一致）：
%   条件一：云团已起爆且仍在有效期内：5.1 <= t <= 5.1 + 20；
%   条件二：云团中心到线段「导弹当前位置 → 真目标 (0,200,5)」的最短距离 ≤ 10 m。
%   两条同时满足 → 1，否则 → 0。
%
% ⚠ 下面参数必须与 main_Q1.m 保持一致，改动请两边同步。
% ⚠ g 取 9.8；若建模手用 9.81，必须两边统一（会影响边界时刻的判定！）。

    %% ---- 参数区（与 main_Q1.m 相同）----
    vM     = 300;                  % 导弹速度 (m/s)
    M1_0   = [20000, 0, 2000];     % M1 起点
    fake   = [0, 0, 0];            % 假目标（导弹直飞的点）
    real_pt= [0, 200, 5];          % 真目标代表点（圆柱中心，任务单提示）
    FY1_0  = [17800, 0, 1800];     % FY1 起点
    vFY    = 120;                  % FY1 速度
    t_drop = 1.5;                  % 投弹时刻 (s)
    t_det  = 5.1;                  % 起爆时刻 (s) = 1.5 + 3.6
    g      = 9.8;                  % 重力加速度 (m/s^2)
    v_sink = 3;                    % 云团下沉速度 (m/s)
    R      = 10;                   % 有效遮蔽半径 (m)
    T_life = 20;                   % 起爆后有效时长 (s)

    %% ---- 条件一：云团是否存在 ----
    flag = 0;
    if t < t_det || t > t_det + T_life
        return;                    % 云团还没形成 / 已失效，直接判 0
    end

    %% ---- 时刻 t 导弹位置 ----
    dirM = (fake - M1_0) / norm(fake - M1_0);
    M    = M1_0 + vM * t * dirM;

    %% ---- 时刻 t 云团中心位置 ----
    % 投放点：1.5 s 时 FY1 的位置（等高度朝假目标飞 → 方向 (-1,0,0)）
    dirFY    = fake - FY1_0;
    dirFY(3) = 0;
    dirFY    = dirFY / norm(dirFY);
    pos_drop = FY1_0 + vFY * t_drop * dirFY;
    % 抛出速度 = 无人机速度，之后仅受重力 → 起爆时刻位置 = 云团中心起点
    v0   = vFY * dirFY;
    tau  = t_det - t_drop;
    C0   = pos_drop + v0 * tau + [0, 0, -0.5 * g * tau^2];
    % 起爆后匀速下沉
    C    = C0 + [0, 0, -v_sink * (t - t_det)];

    %% ---- 条件二：点到线段距离 ----
    d = point_seg_dist(C, M, real_pt);
    if d <= R
        flag = 1;
    end
end

%% ============================================================
function d = point_seg_dist(P, A, B)
% 点 P 到线段 AB 的最短距离（任务单第 6 步要求自己看懂的函数）
% 思路：
%   1) 把向量 AP 投影到 AB 方向上，得到投影参数
%      s = AP·AB / |AB|^2。s 表示最近点在线段上的"百分比位置"：
%      s=0 → 最近点在 A 处，s=1 → 在 B 处，0<s<1 → 在线段内部。
%   2) 若投影落在线段外（s<0 或 s>1），把它夹回 [0,1]，
%      这样算的是到"线段"而不是到"直线"的距离。
%   3) 最近点 Q = A + s·AB，距离 = |P − Q|。
    AB = B - A;
    s  = dot(P - A, AB) / dot(AB, AB);
    if s < 0, s = 0; end
    if s > 1, s = 1; end
    Q  = A + s * AB;
    d  = norm(P - Q);
end
