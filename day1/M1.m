function P = M1(t)
% M1(t) —— 导弹 M1 位置（交接包 §1）
% 从 (20000,0,2000) 以 300 m/s 沿 3D 直线飞向假目标 (0,0,0)。
% 方向单位向量 u = (−20000, 0, −2000)/√(20000²+2000²) ≈ (−0.9950, 0, −0.0995)
% ⚠ 必须用精确的 u，不要手工舍入成 298.5/29.85（对不上 Block4 采样表）。
    u = [-20000, 0, -2000] / sqrt(20000^2 + 2000^2);
    P = [20000, 0, 2000] + 300 * t * u;
end
