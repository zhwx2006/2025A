function P = missile_pos5(m, t)
% missile_pos5 —— 第 m 枚导弹位置（m=1,2,3），向量化（t 为列向量 → N×3）
% 三枚导弹均以 300 m/s 直线飞向假目标 (0,0,0)（精确单位向量）。
% M1(0)=(20000,0,2000)，M2(0)=(19000,600,2100)，M3(0)=(18000,-600,1900)
% 与一页纸系数核对：M2 ≈ (19000−298.04t, 600−9.41t, 2100−32.94t)，
%                   M3 ≈ (18000−298.18t, −600+9.94t, 1900−31.47t)（一致）。
    starts = [20000, 0, 2000;
              19000, 600, 2100;
              18000, -600, 1900];
    u = -starts(m,:) / norm(starts(m,:));
    P = starts(m,:) + 300 * t * u;
end
